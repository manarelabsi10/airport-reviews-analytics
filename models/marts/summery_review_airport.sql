select
   AIRPORT_NAME,
   count(*) as TOTAL_REVIEWS,
   avg(QUEUING_TIMES) as AVG_QUEUING_TIMES,
   avg(TERMINAL_CLEANLINESS) as AVG_TERMINAL_CLEANLINESS,
   avg(TERMINAL_SEATING) as AVG_TERMINAL_SEATING,
   avg(TERMINAL_SIGNS) as AVG_TERMINAL_SIGNS,
   avg(FOOD_BEVERAGES) as AVG_FOOD_BEVERAGES,
   avg(AIRPORT_SHOPPING) as AVG_AIRPORT_SHOPPING,
   avg(WIFI_CONNECTIVITY) as AVG_WIFI_CONNECTIVITY,
   avg(AIRPORT_STAFF) as AVG_AIRPORT_STAFF
from {{ref('stg_AIRPORT_REVIEW')}}
group by AIRPORT_NAME
order by TOTAL_REVIEWS desc

